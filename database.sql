DROP TABLE IF EXISTS Macher;
DROP TABLE IF EXISTS Stylos;
DROP TABLE IF EXISTS Enfants;

CREATE TABLE Enfants (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    num_tel VARCHAR(30),
    date_naissance DATE NOT NULL,
    distance_au_sol INT DEFAULT 50,
    taux_humidite FLOAT DEFAULT 0.7
);
 
 
CREATE TABLE Stylos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    couleur VARCHAR(30) NOT NULL,
    marque VARCHAR(50) NOT NULL,
    niveau_encre INT DEFAULT 100,
    fonctionne BOOLEAN DEFAULT TRUE,
    id_enfant INT
);
 

CREATE TABLE Macher (
     id_stylo INT NOT NULL,
     id_enfant INT NOT NULL,
     PRIMARY KEY (id_stylo, id_enfant)
);


ALTER TABLE Stylos ADD CONSTRAINT fk_proprietaire 
FOREIGN KEY (id_enfant) REFERENCES Enfants(id);
ALTER TABLE Macher ADD CONSTRAINT fk_macheur 
FOREIGN KEY (id_enfant) REFERENCES Enfants(id);
ALTER TABLE Macher ADD CONSTRAINT fk_stylo_mache 
FOREIGN KEY (id_stylo) REFERENCES Stylos(id);

